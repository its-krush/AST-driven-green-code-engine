const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const root = path.resolve(__dirname, '..');
const staging = path.join(root, '.vscode-extension');
fs.rmSync(staging, { recursive: true, force: true });
fs.mkdirSync(path.join(staging, 'extension'), { recursive: true });
fs.mkdirSync(path.join(staging, 'core'), { recursive: true });
fs.mkdirSync(path.join(staging, 'webview'), { recursive: true });
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/extension/package.json'), 'utf8'));
manifest.main = './extension/extension.js';
manifest.repository = { type: 'git', url: 'https://github.com/its-krush/AST-driven-green-code-engine.git' };
fs.writeFileSync(path.join(staging, 'package.json'), JSON.stringify(manifest, null, 2));
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(staging, 'LICENSE'));
fs.writeFileSync(path.join(staging, '.vscodeignore'), '*.map\n*.ts\n');
fs.copyFileSync(path.join(root, 'dist/extension/extension.js'), path.join(staging, 'extension/extension.js'));
fs.copyFileSync(path.join(root, 'dist/extension/companionPanel.js'), path.join(staging, 'extension/companionPanel.js'));
fs.copyFileSync(path.join(root, 'dist/core/index.js'), path.join(staging, 'core/index.js'));
fs.copyFileSync(path.join(root, 'src/extension/webview/companion.js'), path.join(staging, 'webview/companion.js'));
execFileSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['vsce', 'package', '--no-dependencies', '--out', path.join(root, 'ast-green-code-engine.vsix')], { cwd: staging, stdio: 'inherit' });
